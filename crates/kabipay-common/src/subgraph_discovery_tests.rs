use super::*;
use async_graphql::{EmptyMutation, EmptySubscription, Object};
use axum::{
    body::{to_bytes, Body},
    extract::FromRequest,
    http::Request,
};
use std::sync::atomic::{AtomicUsize, Ordering};

struct Query;
#[Object]
impl Query {
    async fn business_value(&self, ctx: &Context<'_>) -> i32 {
        ctx.data_unchecked::<Arc<AtomicUsize>>()
            .fetch_add(1, Ordering::SeqCst);
        42
    }
}

async fn post(query: &str, authorization: Option<&str>) -> (StatusCode, serde_json::Value, usize) {
    post_named(query, authorization, None).await
}

async fn post_named(
    query: &str,
    authorization: Option<&str>,
    operation_name: Option<&str>,
) -> (StatusCode, serde_json::Value, usize) {
    let calls = Arc::new(AtomicUsize::new(0));
    let binding = crate::db::BoundTenantDatabase::from_values(
        Some("00000000-0000-0000-0000-000000000001"),
        Some("postgres://fixture:synthetic@127.0.0.1:1/fixture"),
        Some("tenant_fixture"),
    )
    .unwrap()
    .unwrap();
    let schema = Schema::build(Query, EmptyMutation, EmptySubscription)
        .enable_federation()
        .extension(crate::entitlement_graphql::ModuleEntitlement("EMPLOYEE"))
        .data(TenantDbCache::with_binding(binding))
        .data(calls.clone())
        .finish();
    let mut headers = HeaderMap::new();
    if let Some(value) = authorization {
        headers.insert(header::AUTHORIZATION, value.parse().unwrap());
    }
    let request = Request::builder()
        .method("POST")
        .header("content-type", "application/json")
        .body(Body::from(
            serde_json::json!({"query": query, "operationName": operation_name}).to_string(),
        ))
        .unwrap();
    let request = GraphQLRequest::from_request(request, &())
        .await
        .ok()
        .expect("valid JSON fixture");
    let response = tenant_graphql_post(State(Arc::new(schema)), headers, request)
        .await
        .into_response();
    let status = response.status();
    let body = to_bytes(response.into_body(), 1024 * 1024).await.unwrap();
    let value = serde_json::from_slice(&body).unwrap_or(serde_json::Value::Null);
    (status, value, calls.load(Ordering::SeqCst))
}

#[tokio::test]
async fn anonymous_company_schema_discovery_reaches_graphql_without_business_access() {
    for query in [
        "{ _service { sdl } }",
        "query IntrospectionQuery { __schema { queryType { name } } }",
        "{ __typename }",
    ] {
        let (status, value, calls) = post(query, None).await;
        assert_eq!(status, StatusCode::OK, "{query}");
        assert!(value.get("errors").is_none(), "{value}");
        assert!(!value["data"].is_null(), "{value}");
        assert_eq!(calls, 0);
    }
}

#[tokio::test]
async fn full_gateway_introspection_is_supported_without_a_database() {
    // Generated by the gateway's installed graphql.getIntrospectionQuery().
    let query = include_str!("subgraph_introspection.graphql");
    let (status, value, calls) = post_named(query, None, Some("IntrospectionQuery")).await;
    assert_eq!(status, StatusCode::OK);
    assert!(value.get("errors").is_none(), "{value}");
    assert!(value["data"]["__schema"]["types"].is_array());
    assert_eq!(calls, 0);
}

#[tokio::test]
async fn metadata_children_cannot_hide_business_type_fragments() {
    for query in [
        "{ _service { ... on Query { businessValue } } }",
        "{ __schema { ... on Query { businessValue } } }",
    ] {
        let (status, value, calls) = post(query, None).await;
        assert_eq!(status, StatusCode::OK);
        assert!(value["errors"].is_array(), "{value}");
        assert_eq!(calls, 0);
    }
}

#[tokio::test]
async fn discovery_never_admits_business_or_invalid_bearer() {
    for query in [
        "{ businessValue }",
        "{ _service { sdl } businessValue }",
        "{ _service: businessValue }",
        "{ __typename ...Hidden } fragment Hidden on Query { businessValue @skip(if:true) }",
    ] {
        let (status, _, calls) = post(query, None).await;
        assert_eq!(status, StatusCode::UNAUTHORIZED, "{query}");
        assert_eq!(calls, 0);
    }
    let (status, _, calls) =
        post("{ _service { sdl } }", Some("Bearer invalid.fixture.token")).await;
    assert_eq!(status, StatusCode::UNAUTHORIZED);
    assert_eq!(calls, 0);
}

fn discovery(query: &str, operation: Option<&str>) -> bool {
    let mut request = async_graphql::Request::new(query);
    request.operation_name = operation.map(str::to_owned);
    schema_discovery::is_schema_discovery(&mut request)
}

#[test]
fn discovery_classifies_actual_fields_and_selected_operations() {
    for query in [
        "{ businessLookingAlias: _service { sdl } }",
        "query Named { ...Metadata } fragment Metadata on Query { ... on Query { __schema { queryType { name } } } }",
        "query Type($name:String!){ __type(name:$name){ name fields { name } } }",
        "{ _service { ...Fields } } fragment Fields on _Service { sdl }",
    ] { assert!(discovery(query, None), "{query}"); }
    let two = "query Metadata { __typename } query Business { businessValue }";
    assert!(discovery(two, Some("Metadata")));
    assert!(!discovery(two, Some("Business")));
    assert!(!discovery(two, None));
    assert!(!discovery(two, Some("Missing")));
    assert!(!discovery("{ __typename }", Some("Named")));
    assert!(discovery("query Named { __typename }", Some("Named")));
    for query in [
        "{ _service: businessValue }",
        "{ _entities(representations:[]) { __typename } }",
        "mutation { __typename }",
        "subscription { __typename }",
        "{ __typename businessValue @skip(if:true) }",
        "{ __typename ... on Query { businessValue } }",
        "{ __typename ...Hidden } fragment Hidden on Query { businessValue }",
        "# __schema _service\n{ businessValue }",
        "query Q($s:String=\"_service\"){ businessValue }",
        "{ __schemaBroken }",
        "{ _serviceBroken }",
        "{ __typename ...Missing }",
        "{",
        "{ ...A } fragment A on Query { ...B } fragment B on Query { ...A }",
        "{ _service { ...A } } fragment A on _Service { ...A }",
    ] {
        assert!(!discovery(query, None), "{query}");
    }
}

#[test]
fn discovery_bounds_document_and_fragment_expansion_work() {
    assert!(!discovery(
        &format!("{{ __typename }}#{}", "x".repeat(65536)),
        None
    ));
    assert!(!discovery(
        &format!("{{ {} }}", "__typename ".repeat(2049)),
        None
    ));
    let mut query = String::from("{ ...F0 }");
    for index in 0..34 {
        query.push_str(&format!(
            " fragment F{index} on Query {{ ...F{} }}",
            index + 1
        ));
    }
    query.push_str(" fragment F34 on Query { __typename }");
    assert!(!discovery(&query, None));
    let mut query = String::from("{ ...F0 }");
    for index in 0..12 {
        query.push_str(&format!(
            " fragment F{index} on Query {{ ...F{} ...F{} }}",
            index + 1,
            index + 1
        ));
    }
    query.push_str(" fragment F12 on Query { __typename }");
    assert!(!discovery(&query, None));
}
